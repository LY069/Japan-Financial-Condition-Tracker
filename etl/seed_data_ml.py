def main():
    conn = connect()
    init_db(conn)
    load_catalog(conn)
    n = 0
    for sid, rows in build().items():
        live = conn.execute("SELECT COUNT(*) FROM observations WHERE series_id=? AND source!='SEED'",
                            (sid,)).fetchone()[0]
        if live:
            print(f"  {sid}: {live} live obs present, seed skipped")
            continue
        n += upsert_observations(conn, sid, rows, "SEED")
    print(f"Seeded M&L series: {n} observations.")


if __name__ == "__main__":
    main()
